-- Panel de super admin: empresa activa, estado de organizacion, borrado completo,
-- tarifas y perfiles de calculo por organizacion.
-- Ver docs/superpowers/specs/2026-11-11-panel-super-admin-design.md

-- 1. Empresa activa del super admin. Solo tiene efecto cuando is_super_admin.
alter table public.profiles
  add column if not exists acting_organization_id uuid references public.organizations(id) on delete set null;

create or replace function public.current_organization_id()
returns uuid
language sql
stable
security definer
set search_path = public
as $$
  select case when is_super_admin then acting_organization_id else organization_id end
  from public.profiles
  where id = auth.uid();
$$;

-- Un admin de empresa tampoco puede tocar acting_organization_id (no le serviria,
-- pero mejor que ni lo intente).
create or replace function public.guard_profile_privileges()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is not null
     and not public.is_super_admin()
     and (
       new.is_super_admin is distinct from old.is_super_admin
       or new.organization_id is distinct from old.organization_id
       or new.acting_organization_id is distinct from old.acting_organization_id
     ) then
    raise exception 'No autorizado a modificar privilegios de plataforma';
  end if;
  return new;
end;
$$;

-- 2. Estado de la organizacion. Suspendida = sus usuarios no leen ni escriben.
alter table public.organizations
  add column if not exists status text not null default 'active' check (status in ('active', 'suspended'));

create or replace function public.current_account_status()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select case when o.status = 'suspended' then 'suspended' else p.status end
  from public.profiles p
  left join public.organizations o on o.id = p.organization_id
  where p.id = auth.uid();
$$;

-- 3. Borrado completo de una organizacion (datos, archivos, usuarios). Solo super admin.
-- Los usuarios se borran de auth.users: profiles cae en cascada y no pueden volver a entrar.
create or replace function public.delete_organization(target uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  t text;
begin
  if not public.is_super_admin() then
    raise exception 'Solo el super admin puede borrar organizaciones';
  end if;

  foreach t in array array[
    'lead_tasks', 'lead_interactions', 'captured_leads', 'audit_log', 'document_files',
    'document_counters', 'tasks', 'employees', 'invoices', 'purchase_orders', 'inventory_items',
    'work_orders', 'quotes', 'opportunities', 'companies', 'labor_rate_catalog', 'quote_calculation_profiles'
  ] loop
    execute format('delete from public.%I where organization_id = $1', t) using target;
  end loop;

  delete from storage.objects
  where bucket_id = 'erp-documents' and (storage.foldername(name))[1] = target::text;

  update public.profiles set acting_organization_id = null where acting_organization_id = target;
  delete from auth.users where id in (select id from public.profiles where organization_id = target);
  delete from public.organizations where id = target;
end;
$$;

revoke execute on function public.delete_organization(uuid) from anon, public;
grant execute on function public.delete_organization(uuid) to authenticated;

-- 4. Tarifas y perfiles de calculo: la clave de negocio (id texto) pasa a ser unica
-- por organizacion, con un id tecnico como PK (mismo patron que el cierre).
do $$
declare
  t text;
begin
  foreach t in array array['labor_rate_catalog', 'quote_calculation_profiles'] loop
    execute format('alter table public.%I add column if not exists row_id bigint generated by default as identity', t);
    execute format('alter table public.%I drop constraint if exists %I', t, t || '_pkey');
    execute format('alter table public.%I add primary key (row_id)', t);
    execute format('alter table public.%I drop constraint if exists %I', t, t || '_org_id_key');
    execute format('alter table public.%I add constraint %I unique (organization_id, id)', t, t || '_org_id_key');
  end loop;
end $$;

-- 5. El super admin operando una empresa tiene permisos de admin sin importar su
-- profiles.role (el bootstrap solo setea is_super_admin; el rol puede ser 'ventas').
create or replace function public.can_read_module(module text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select case
    when auth.uid() is null then false
    when public.is_super_admin() then true
    when public.current_account_status() <> 'active' then false
    when public.current_role() in ('admin', 'direccion') then true
    when module in ('quotes', 'work_orders') and public.current_role() = 'cliente' then true
    when module in ('companies', 'opportunities', 'quotes') and public.current_role() = 'ventas' then true
    when module in ('work_orders', 'inventory_items') and public.current_role() = 'operaciones' then true
    when module in ('inventory_items', 'purchase_orders') and public.current_role() = 'compras' then true
    when module in ('companies', 'opportunities', 'invoices', 'quotes') and public.current_role() = 'finanzas' then true
    when module = 'employees' and public.current_role() = 'rrhh' then true
    when module = 'tasks' and public.current_role() in ('admin', 'direccion', 'ventas', 'operaciones', 'compras', 'finanzas', 'rrhh') then true
    when module = 'document_files' and public.current_role() in ('admin', 'direccion', 'ventas', 'operaciones', 'compras', 'finanzas') then true
    else false
  end;
$$;

