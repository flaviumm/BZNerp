-- Cierre de seguridad multiempresa.
-- Ver docs/superpowers/specs/2026-11-10-cierre-erp-design.md
-- No borra filas: solo cambia policies, funciones y claves unicas.

-- 1. Catalogo global de materiales: lo escribe solo el super admin (el sync
-- nocturno usa service role, que no pasa por RLS). Antes cualquier usuario con
-- rol compras de cualquier organizacion podia pisar precios que usan todas.
drop policy if exists "material_price_catalog_write_admin" on public.material_price_catalog;
drop policy if exists "material_price_catalog_write_super_admin" on public.material_price_catalog;
create policy "material_price_catalog_write_super_admin" on public.material_price_catalog
for all
using (public.is_super_admin())
with check (public.is_super_admin());

-- 2. Un usuario autenticado sin organizacion (super admin de plataforma) no
-- puede insertar datos operativos: quedarian con organization_id NULL,
-- invisibles para todos. Service role (auth.uid() null) sigue pasando.
create or replace function public.set_organization_id()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.organization_id is null then
    new.organization_id := public.current_organization_id();
  end if;
  if new.organization_id is null and auth.uid() is not null then
    raise exception 'El usuario no tiene organizacion asignada';
  end if;
  return new;
end;
$$;

-- 3. El rol cliente no ve presupuestos en borrador (el cotizador autoguarda
-- borradores como filas reales de quotes).
drop policy if exists "quotes_read_by_role" on public.quotes;
create policy "quotes_read_by_role" on public.quotes for select
using (
  public.is_super_admin()
  or (
    organization_id = public.current_organization_id()
    and public.can_read_module('quotes')
    and (
      public.current_role() <> 'cliente'
      or (client = public.current_company_name() and status <> 'Borrador')
    )
  )
);

-- 4. Unicidad por organizacion. Los numeros de documento se generan por
-- organizacion (next_document_number), pero las claves eran globales: la
-- segunda empresa chocaba en P-0001. Se agrega un id tecnico como PK y la
-- clave de negocio pasa a ser (organization_id, numero).
do $$
declare
  t text;
  col text;
begin
  for t, col in
    select * from (values
      ('quotes', 'number'),
      ('work_orders', 'number'),
      ('purchase_orders', 'number'),
      ('invoices', 'number'),
      ('inventory_items', 'sku')
    ) as v(t, col)
  loop
    execute format('alter table public.%I add column if not exists id bigint generated by default as identity', t);
    execute format('alter table public.%I drop constraint if exists %I', t, t || '_pkey');
    execute format('alter table public.%I add primary key (id)', t);
    execute format('alter table public.%I drop constraint if exists %I', t, t || '_org_' || col || '_key');
    execute format('alter table public.%I add constraint %I unique (organization_id, %I)', t, t || '_org_' || col || '_key', col);
  end loop;
end $$;

drop index if exists public.companies_name_unique;
create unique index if not exists companies_org_name_unique on public.companies (organization_id, name);

drop index if exists public.employees_name_unique;
create unique index if not exists employees_org_name_unique on public.employees (organization_id, name);

drop index if exists public.opportunities_company_service_unique;
create unique index if not exists opportunities_org_company_service_unique on public.opportunities (organization_id, company, service);

drop index if exists public.tasks_text_owner_due_unique;
create unique index if not exists tasks_org_text_owner_due_unique on public.tasks (organization_id, text, owner, due);

-- 5. Finanzas lee clientes y oportunidades (solo lectura) para Reportes.
-- Resto identico a 20260510213000_harden_rls_rpc.sql.
create or replace function public.can_read_module(module text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select case
    when auth.uid() is null then false
    when public.current_account_status() <> 'active' then false
    when public.current_role() in ('admin', 'direccion') then true
    when module in ('quotes', 'work_orders') and public.current_role() = 'cliente' then true
    when module in ('companies', 'opportunities', 'quotes') and public.current_role() = 'ventas' then true
    when module in ('work_orders', 'inventory_items') and public.current_role() = 'operaciones' then true
    when module in ('inventory_items', 'purchase_orders') and public.current_role() = 'compras' then true
    when module in ('companies', 'opportunities', 'invoices', 'quotes') and public.current_role() = 'finanzas' then true
    when module = 'employees' and public.current_role() = 'rrhh' then true
    when module = 'tasks' and public.current_role() in ('admin', 'direccion', 'ventas', 'operaciones', 'compras', 'finanzas', 'rrhh') then true
    when module = 'document_files' and public.current_role() in ('admin', 'direccion', 'ventas', 'operaciones', 'compras', 'finanzas') then true
    else false
  end;
$$;
